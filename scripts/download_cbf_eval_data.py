"""Download pinned-name public benchmark inputs into a separate evaluation folder.

RULER and RULER/QA are generated by the baseline OpenCompass configuration,
so they do not have one fixed JSON file to fetch here.
"""

import argparse
import hashlib
import json
import urllib.request
from pathlib import Path


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    from datasets import load_dataset
    from huggingface_hub import hf_hub_download

    root = Path(args.output)
    root.mkdir(parents=True, exist_ok=True)
    manifest = {}

    sources = (
        ("zsre", "zjunlp/KnowEdit", "benchmark/ZsRE/ZsRE-test-all.json"),
        ("longmemeval_s", "xiaowu0162/longmemeval-cleaned", "longmemeval_s_cleaned.json"),
    )
    for name, repo, filename in sources:
        folder = root / name
        path = Path(hf_hub_download(repo_id=repo, repo_type="dataset", filename=filename,
                                    local_dir=folder))
        manifest[name] = {"repo": repo, "file": str(path), "sha256": sha256(path),
                          "bytes": path.stat().st_size}

    locomo_url = "https://raw.githubusercontent.com/snap-research/locomo/main/data/locomo10.json"
    locomo_path = root / "locomo" / "locomo10.json"
    locomo_path.parent.mkdir(parents=True, exist_ok=True)
    urllib.request.urlretrieve(locomo_url, locomo_path)
    manifest["locomo"] = {"url": locomo_url, "file": str(locomo_path),
                          "sha256": sha256(locomo_path), "bytes": locomo_path.stat().st_size}

    mmlu_folder = root / "mmlu"
    mmlu_folder.mkdir(parents=True, exist_ok=True)
    for split in ("dev", "test"):
        dataset = load_dataset("cais/mmlu", "all", split=split)
        output = mmlu_folder / f"{split}.jsonl"
        with output.open("w", encoding="utf-8") as sink:
            for row in dataset:
                sink.write(json.dumps(row, ensure_ascii=False) + "\n")
        manifest[f"mmlu_{split}"] = {"repo": "cais/mmlu", "config": "all",
                                    "split": split, "file": str(output),
                                    "rows": len(dataset), "sha256": sha256(output),
                                    "bytes": output.stat().st_size}

    manifest["ruler"] = {"generator": "eval_config/ruler_*.py via OpenCompass"}
    manifest["ruler_qa"] = {"generator": "qa_datasets imported in eval_config/ruler_*.py"}
    manifest_path = root / "MANIFEST.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                             encoding="utf-8")
    print(json.dumps({"manifest": str(manifest_path), "datasets": list(manifest)},
                     ensure_ascii=False))


if __name__ == "__main__":
    main()
